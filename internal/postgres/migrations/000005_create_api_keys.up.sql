CREATE TABLE atlas_api_keys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id text NOT NULL UNIQUE,
    key_hash bytea NOT NULL CHECK (octet_length(key_hash) = 32),
    name varchar(100) NOT NULL,
    role_name text NOT NULL REFERENCES atlas_roles(role_name) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_key_id bigint REFERENCES atlas_api_keys(id) ON DELETE SET NULL,
    revoked_at timestamptz,
    revoked_by_key_id bigint REFERENCES atlas_api_keys(id) ON DELETE SET NULL,
    last_used_at timestamptz,
    role_changed_at timestamptz,
    role_changed_by_key_id bigint REFERENCES atlas_api_keys(id) ON DELETE SET NULL
);
