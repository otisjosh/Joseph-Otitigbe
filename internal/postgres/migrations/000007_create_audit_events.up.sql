CREATE TABLE atlas_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    actor_key_id bigint REFERENCES atlas_api_keys(id) ON DELETE SET NULL,
    action text NOT NULL,
    resource_type text NOT NULL CHECK (resource_type IN ('record', 'api_key')),
    resource_id bigint,
    details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object')
);
CREATE INDEX atlas_audit_events_occurred_id_idx ON atlas_audit_events (occurred_at DESC, id DESC);
